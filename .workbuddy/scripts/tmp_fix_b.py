def insert_after_h2(text, h2, para):
    pat = re.compile(r"(?m)^" + re.escape(h2) + r"[ \t]*$")
    m = pat.search(text)
    if not m:
        return text, False
    start = m.end()
    nxt = re.search(r"(?m)^(## |\[封面图提示词\]|---[ \t]*$)", text[start:])
    end = start + nxt.start() if nxt else len(text)
    block = text[start:end].rstrip("\n")
    new = block + "\n\n" + para + "\n\n"
    return text[:start] + new + text[end:], True


