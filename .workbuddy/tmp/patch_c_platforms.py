def patch(fname, inserts):
    p = os.path.join(base, fname)
    c = open(p, encoding='utf-8').read()
    for anchor, add in inserts:
        if anchor not in c:
            print('  [WARN] %s: %s' % (fname, anchor[:25]))
            continue
        c = c.replace(anchor, anchor + '\n\n' + add, 1)
    open(p, 'w', encoding='utf-8').write(c)
    body = c.split('---', 2)[2]
    cut = body.find('## 配图搜索替换指令')
    if cut < 0:
        cut = body.find('[封面图提示词]')
    body = body[:cut]
    lines = [l for l in body.split('\n') if not l.strip().startswith('#')]
    cnt = sum(len(re.findall(r'[\u4e00-\u9fff]', l)) for l in lines)
    print('%s: %s' % (fname, cnt))

